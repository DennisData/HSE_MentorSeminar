#!/bin/bash

# Запускаем три команды sleep в фоновом режиме
sleep 10 &
sleep 20 &
sleep 30 &

# Получаем список фоновых задач
jobs

# Переводим первую задачу на передний план
fg %1

# Наблюдаем за выполнением задачи
echo "Первая задача выполняется"

# Переводим задачу обратно в фоновый режим
bg %1

# Получаем список фоновых задач
jobs

# Переводим вторую задачу на передний план
fg %2

# Наблюдаем за выполнением задачи
echo "Вторая задача выполняется"

# Переводим задачу обратно в фоновый режим
bg %2

# Переводим третью задачу на передний план
fg %3

# Наблюдаем за выполнением задачи
echo "Третья задача выполняется"

# Переводим задачу обратно в фоновый режим
bg %3

# Получаем список фоновых задач
jobs

# Завершаем все фоновые задачи
kill %1 %2 %3

# Проверяем, что все задачи завершены
jobs